#!/usr/bin/env node
// Copies the runtime-neutral MCP core (mcp/core.mjs) and the Topics helpers (topics.js, wrapped as an ES module)
// into supabase/functions/grok-mcp/ so the Edge Function bundle is self-contained.
//   node scripts/build-mcp-function.mjs          (write)   |   --check   (exit 1 if the copies are stale; used by tests)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "supabase/functions/grok-mcp");
const HEAD = src => `// GENERATED by scripts/build-mcp-function.mjs from ${src} — do not edit; run the script instead.\n`;
export function generated() {
  return {
    "core.mjs": HEAD("mcp/core.mjs") + fs.readFileSync(path.join(root, "mcp/core.mjs"), "utf8"),
    "topics.mjs": HEAD("topics.js") + "const module = { exports: {} };\n" + fs.readFileSync(path.join(root, "topics.js"), "utf8") + "\nexport default module.exports;\n",
  };
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [name, text] of Object.entries(generated())) {
    const file = path.join(out, name);
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (cur === text) continue;
    if (check) { stale++; console.error(`stale: supabase/functions/grok-mcp/${name}`); } else { fs.writeFileSync(file, text); console.log(`wrote supabase/functions/grok-mcp/${name}`); }
  }
  process.exit(stale ? 1 : 0);
}
